#!/usr/bin/env python3
"""The N64 stack model's hooks.

  frames.py export BUILD_DIR TARGET SYMBOLS_TSV OUT_TSV
  frames.py wrappers TABLE_TSV OUT_DIR RELATIVE=COMPILED...

The model has to be right wherever the original leaks a stack address: inside
set_camera_mode (docs/avoid_ub.md). So every function from which the N64 can
call set_camera_mode, and set_camera_mode itself, moves the modelled stack
pointer by its N64 frame; nothing else does.

export reads which functions those are, and their frame sizes, from a matching
build of n64decomp/sm64 (BUILD_DIR/TARGET, e.g. build/jp, sm64.jp; see
callgraph.py), with the game thread's stack pointer from SYMBOLS_TSV, and
writes them to OUT_TSV (tools/n64stack/<version>.tsv, committed).

wrappers runs at configure time. For each game source RELATIVE
(src/game/mario.c, compiled from COMPILED) that holds such functions, it
writes OUT_DIR/RELATIVE, a wrapper that includes COMPILED and registers those
functions' frame sizes with the host (platform/n64stack.c), and prints

  RELATIVE<TAB>OUT_DIR/RELATIVE<TAB>comma separated functions not to hook

for CMake to compile the wrapper with -finstrument-functions instead. It also
writes OUT_DIR/n64_frames.h with the game thread's stack pointer.
"""
import re
import sys
from pathlib import Path

TARGET = "set_camera_mode"

# Goddard's function pointers only lead to goddard: its indirect calls do not
# reach the game.
GODDARD = "/src/goddard/"


def export(build, target, symbols, out):
    sys.path.insert(0, str(Path(__file__).parent))
    import callgraph

    funcs, graph = callgraph.call_graph(
        build, target, lambda caller, callee: GODDARD not in caller.object or GODDARD in callee.object)
    targets = [f for f in funcs if f.name == TARGET]
    hooked = callgraph.ancestors(graph, targets) | set(targets)

    # The game thread's stack: osCreateThread starts it 16 bytes below the top
    # given by create_thread (gThread5Stack + 0x2000).
    stack = None
    for line in Path(symbols).read_text().splitlines():
        parts = line.split("\t")
        if parts[0] == "gThread5Stack":
            stack = int(parts[1], 16) + int(parts[2])
    loop = next(f for f in funcs if f.name == "thread5_game_loop")
    prefix = f"{Path(build).relative_to(Path(build).parent.parent)}/"
    lines = [
        f"# Generated by tools/n64stack/frames.py export from {prefix}{target}.elf. Functions on the",
        f"# N64's call paths to {TARGET}, with their stack frame sizes.",
        f"game_loop_sp\t0x{stack - 16 - loop.frame:08x}",
    ]
    for f in sorted(hooked, key=lambda f: (f.object, f.address)):
        source = f.object[len(prefix):-2] + ".c"
        lines.append(f"{source}\t{f.name}\t{f.frame}")
    Path(out).write_text("\n".join(lines) + "\n")


def defined_functions(path, seen=None):
    """Names of the functions a C file defines, with the .c files it includes."""
    seen = seen if seen is not None else set()
    path = Path(path)
    if path in seen or not path.exists():
        return set()
    seen.add(path)
    text = re.sub(r"\bBAD_RETURN\((\w+)\)", r"\1", path.read_text(errors="replace"))
    names = set(re.findall(r"^[A-Za-z_][\w \t\*]*?\b(\w+)\s*\([^;{}]*\)\s*\{", text, re.M))
    for include in re.findall(r'^#include\s+"([^"]+\.c)"', text, re.M):
        names |= defined_functions(path.parent / include, seen)
    return names


def write_if_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def wrappers(table, out, sources):
    by_source, game_loop_sp = {}, None
    for line in Path(table).read_text().splitlines():
        if line.startswith("#"):
            continue
        fields = line.split("\t")
        if fields[0] == "game_loop_sp":
            game_loop_sp = fields[1]
        else:
            by_source.setdefault(fields[0], []).append((fields[1], int(fields[2])))

    for relative, compiled in sorted(sources.items()):
        functions = by_source.pop(relative, [])
        if not functions:
            continue
        wrapper = out / relative
        wrapper.parent.mkdir(parents=True, exist_ok=True)
        table_name = "sN64Frames_" + re.sub(r"\W", "_", relative[:-2])
        lines = [
            "// Generated by tools/n64stack/frames.py. Do not edit.",
            f'#include "{compiled}"',
            '#include "n64stack.h"',
            "",
            f"static const struct n64_frame {table_name}[] = {{",
        ]
        lines += [f"    {{ (const void *) {name}, {frame} }}," for name, frame in functions]
        lines += ["};", "", f"N64STACK_REGISTER({table_name[11:]}, {table_name})", ""]
        write_if_changed(wrapper, "\n".join(lines))
        names = {name for name, _ in functions}
        # GCC excludes every function whose name contains one of the list's:
        # names inside a hooked one's stay hooked, with no frame (a lookup).
        excluded = sorted(e for e in defined_functions(compiled) - names if not any(e in n for n in names))
        print(f"{relative}\t{wrapper}\t{','.join(excluded)}")
    for source in sorted(by_source):
        if not source.startswith("lib/"):
            print(f"frames.py: {source} has functions on the path to {TARGET} but is not compiled",
                  file=sys.stderr)

    out.mkdir(parents=True, exist_ok=True)
    write_if_changed(out / "n64_frames.h",
                     "// Generated by tools/n64stack/frames.py. Do not edit.\n#pragma once\n"
                     "// The N64 stack pointer inside thread5_game_loop.\n"
                     f"#define N64_GAME_LOOP_SP {game_loop_sp}u\n")


def main():
    if len(sys.argv) >= 6 and sys.argv[1] == "export":
        export(*sys.argv[2:6])
    elif len(sys.argv) >= 4 and sys.argv[1] == "wrappers":
        wrappers(Path(sys.argv[2]), Path(sys.argv[3]), dict(spec.split("=", 1) for spec in sys.argv[4:]))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
